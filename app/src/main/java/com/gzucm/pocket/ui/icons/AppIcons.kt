 * 用 SVG path 串拼一个 24dp 的单色 ImageVector。
 *
 * 走 `PathParser` 而不是一条条 `moveTo`/`curveTo`：从官方 path 数据搬过来时
 * 只要原样贴字符串，不用把每个坐标改写成 Kotlin 调用，也不会因为手抄漏一位数
 * 让笔画变形。
 */
private fun icon(name: String, vararg d: String): ImageVector =
    ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
    ).apply {
        d.forEach { path ->
            addPath(
                pathData = PathParser().parsePathString(path).toNodes(),
                fill = SolidColor(Color.Black),
            )
        }
    }.build()
