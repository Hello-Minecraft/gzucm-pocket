package com.gzucm.pocket.core

import java.time.LocalDate

/**
 * 内置的**冲突测试数据**（临时，仅用于验证时间重叠的排版）。
 *
 * 为什么要有这个文件：
 * 重叠课表在真实教务系统里很罕见，等它自然出现再调排版不现实。
 * 所以把四种典型交叠形态固定下来，装包就能直接看到效果，
 * 不用登录、不用联网、不用等某一周。
 *
 * 怎么关掉：把 [Enabled] 改成 false 并重新打包，就回到真实同步。
 */
object ConflictDemo {

    /** 总开关。false = 用真实数据 */
    const val Enabled = false

    /**
     * 学期锚点：把「本周」对到第 8 周，方便直接看到数据。
     * 取一个很久以前的周一，weekOf 会算出很大的数，所以这里用「今天往回推 7 周」。
     */
    fun semester(): Semester {
        val today = LocalDate.now()
        // 本周一 = 今天减掉 (星期几 - 1) 天
        val monday = today.minusDays((today.dayOfWeek.value - 1).toLong())
        // 往回推 7 周，让「本周」正好落在第 8 周
        val firstMonday = monday.minusWeeks(7)
        return Semester.of(
            code = "demo",
            name = "2026-2027 学年 第一学期（冲突演示）",
            firstMonday = firstMonday,
            totalWeeks = 20,
        )
    }

    /**
     * 四列各覆盖一种交叠形态，都在第 8 周。
     *
     * 周一：完全包含（长课里套一门短课）
     * 周二：部分重叠（错开一半）
     * 周三：首节相同、长度差很多（最容易看出分列效果）
     * 周四：三门互相交叠（考验三列时的字号）
     */
    fun sessions(): List<CourseSession> {
        fun c(
            name: String, wd: Int, ps: Int, pe: Int,
            t1: String, t2: String, room: String, cat: String = "理论教学",
        ) = CourseSession(
            name = name, code = "DEMO", teachers = "演示教师",
            week = 8, weekday = wd, startUnit = ps, endUnit = pe,
            startTime = t1, endTime = t2, room = room, category = cat,
        )

        return listOf(
            // ① 完全包含：1-4 的长课里嵌了一门 2-3 的短课
            c("毛泽东思想和中国特色社会主义理论体系概论", 1, 1, 4, "08:30", "11:50", "综教楼B202（智慧课室）"),
            c("医学伦理学", 1, 2, 3, "09:20", "11:00", "新课室楼301"),

            // ② 部分重叠：3-5 与 4-6 错开一半
            c("岭南骨伤康复学", 2, 3, 5, "10:20", "13:00", "教学楼B214"),
            c("中医骨伤科学", 2, 4, 6, "11:10", "13:50", "教学楼B212（智慧课室）"),

            // ③ 首节相同、长度差很多：6-10 与 6-7
            c("大学心理健康教育", 3, 6, 10, "14:00", "17:40", "户外拓展实验基地"),
            c("马拉松运动医学", 3, 6, 7, "14:00", "15:30", "教学楼B212（智慧课室）"),

            // ④ 三门互相交叠：第 3 节三门同时在，必须分三列
            c("方剂学", 4, 1, 3, "08:30", "11:00", "综教楼305"),
            c("中药学", 4, 2, 5, "09:20", "13:00", "综教楼306"),
            c("中医诊断学", 4, 3, 6, "10:20", "13:50", "综教楼307"),

            // ⑥ 完全重叠：两门课节次一模一样，最能暴露轮换是否真的生效
            //    放在周六（weekday=6），避开前面几列
            c("中医基础理论", 6, 1, 3, "08:30", "11:00", "综教楼301"),
            c("内经选读", 6, 1, 3, "08:30", "11:00", "综教楼302"),

            // ⑦ 完全重叠且只有一节：宽度最紧张的情况（周日）
            c("医学统计学", 7, 3, 3, "10:20", "11:00", "新课室楼105"),
            c("流行病学", 7, 3, 3, "10:20", "11:00", "新课室楼106"),

            // ⑧ 三门完全重叠（周日 6-8 节）：验证 A-B-C → B-C-A 轮换，点三次回到原样
            c("温病学", 7, 6, 8, "14:00", "16:20", "综教楼401"),
            c("金匮要略", 7, 6, 8, "14:00", "16:20", "综教楼402"),
            c("伤寒论", 7, 6, 8, "14:00", "16:20", "综教楼403"),

            // ⑦ 对照组：完全没有冲突，用来确认正常排版没被改坏
            c("中医妇科学", 5, 1, 2, "08:30", "10:00", "新课室楼302"),
            c("中医儿科学", 5, 3, 4, "10:20", "11:50", "综教楼808（智慧课室）"),
            c("外科学(2)", 5, 6, 8, "14:00", "16:20", "一附院结直肠外科", "实验教学"),
        )
    }
}